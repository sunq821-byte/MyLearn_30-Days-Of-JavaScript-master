// 声明数字数据类型

let age = 35
const gravity = 9.81  // 我们使用const表示不变的值，重力常数，单位m/s²
let mass = 72         // 质量，单位千克
const PI = 3.14       // 圆周率，几何常数

// 更多示例
const boilingPoint = 100 // 温度，单位°C，水的沸点，是常数
const bodyTemp = 37      // °C，平均人体温度，是常数

console.log(age, gravity, mass, PI, boilingPoint, bodyTemp)