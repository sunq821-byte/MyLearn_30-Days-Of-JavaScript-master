// 数字示例 (整数)
let exampleInteger = 42;
console.log("整数示例:", exampleInteger);

// 数字示例 (浮点数)
let exampleFloat = 3.14;
console.log("浮点数示例:", exampleFloat);

// 布尔值示例
let exampleBoolean = true;
console.log("布尔值示例:", exampleBoolean);

// undefined 示例
let exampleUndefined;
console.log("undefined 示例:", exampleUndefined);

// Null 示例
let exampleNull = null;
console.log("Null 示例:", exampleNull);

// Symbol 示例
let exampleSymbol = Symbol("这是一个符号");
console.log("Symbol 示例:", exampleSymbol);

// 对象示例 (非原始数据类型，但作为补充)
